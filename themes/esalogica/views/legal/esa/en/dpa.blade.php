<p>This agreement forms part of the contract between Esalogica and the Customer (<a href="{{ route('legal.show', 'terms') }}">Terms of Service</a>, art. 15.2) and governs the processing of the personal data the Customer stores in the services, under art. 28 of Regulation (EU) 2016/679 ("GDPR").</p>

<h2>1. Roles</h2>
<p>For the data in the Customer's websites, mailboxes, databases and virtual servers, the Customer is the controller (or processor, where it processes the data on behalf of its own clients) and {{ $esaCompany['legal_name'] }} is its processor (or sub-processor).</p>

<h2>2. Subject matter, duration, nature and purpose</h2>
<ul>
    <li><strong>Subject matter and nature</strong>: storing, transmitting, backing up and deleting the data on the Provider's servers, as far as needed to provide the services.</li>
    <li><strong>Duration</strong>: that of the contract, plus the time needed for deletion set out in point 7.</li>
    <li><strong>Purpose</strong>: solely the provision of the services ordered by the Customer.</li>
    <li><strong>Types of data and data subjects</strong>: those the Customer chooses to store in the services, relating to its clients, users, employees and correspondents. The Provider does not know their content and does not examine it, except as set out in point 3.</li>
</ul>

<h2>3. Provider's obligations</h2>
<p>The Provider:</p>
<ul>
    <li>processes the data only on the Customer's documented instructions, which are the contract and the operations the Customer carries out with the services, unless the law requires otherwise;</li>
    <li>accesses the data only when needed to provide the services, to solve a problem reported by the Customer, or to protect the security of the servers;</li>
    <li>ensures that the persons authorised to process the data are bound by confidentiality;</li>
    <li>takes the appropriate security measures required by art. 32 GDPR, including server access restricted to technical staff with authentication, encrypted connections, security updates, account isolation and backups;</li>
    <li>assists the Customer, as far as possible, in answering data subjects' requests and in the obligations of arts. 32-36 GDPR;</li>
    <li>informs the Customer without undue delay, and in any case within 48 hours of becoming aware of it, of any personal data breach affecting its data;</li>
    <li>makes available to the Customer the information needed to demonstrate compliance with this agreement and allows audits, agreed with reasonable notice and at the Customer's expense.</li>
</ul>

<h2>4. Customer's obligations</h2>
<p>The Customer warrants that it processes the data it stores in the services in compliance with the GDPR, that it has a legal basis to do so and that it has informed the data subjects.</p>

<h2>5. Sub-processors</h2>
<p>The Customer authorises the Provider to use the following sub-processors, which host the servers:</p>
<ul>
    <li>Leaseweb Deutschland GmbH, Frankfurt (Germany);</li>
    <li>Leaseweb Netherlands B.V., Amsterdam (the Netherlands);</li>
    <li>WorldStream B.V., Naaldwijk (the Netherlands).</li>
</ul>
<p>The Provider imposes on them data protection obligations equivalent to those of this agreement. It informs the Customer by email of any new sub-processor at least 30 days in advance; a Customer who objects on data protection grounds may withdraw from the service concerned at no cost.</p>

<h2>6. Place of processing</h2>
<p>The data is stored on servers in the European Union. The Provider does not transfer it outside the European Union without the safeguards required by Chapter V of the GDPR.</p>

<h2>7. End of processing</h2>
<p>When a service ends the Customer may download its data until expiry. The Provider then deletes the data under the terms of the Terms of Service (arts. 6.3 and 7.6); copies in backups are overwritten within the backup retention period (art. 9.3), unless the law requires them to be kept.</p>
