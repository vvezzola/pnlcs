<p>Questo accordo fa parte del contratto tra Esalogica e il Cliente (<a href="{{ route('legal.show', 'terms') }}">Condizioni generali di servizio</a>, art. 15.2) e regola il trattamento dei dati personali che il Cliente conserva nei servizi, ai sensi dell'art. 28 del Regolamento (UE) 2016/679 («GDPR»).</p>

<h2>1. Ruoli</h2>
<p>Per i dati contenuti nei siti, nelle caselle email, nei database e nei server virtuali del Cliente, il Cliente è titolare del trattamento (o responsabile, se tratta i dati per conto dei propri clienti) ed {{ $esaCompany['legal_name'] }} ne è responsabile (o sub-responsabile).</p>

<h2>2. Oggetto, durata, natura e finalità</h2>
<ul>
    <li><strong>Oggetto e natura</strong>: conservazione, trasmissione, backup e cancellazione dei dati sui server del Fornitore, nella misura necessaria a fornire i servizi.</li>
    <li><strong>Durata</strong>: quella del contratto, più il tempo necessario alla cancellazione indicato al punto 7.</li>
    <li><strong>Finalità</strong>: solo l'erogazione dei servizi ordinati dal Cliente.</li>
    <li><strong>Tipi di dati e interessati</strong>: quelli che il Cliente decide di conservare nei servizi, relativi ai suoi clienti, utenti, dipendenti e corrispondenti. Il Fornitore non ne conosce il contenuto e non lo esamina, salvo quanto previsto al punto 3.</li>
</ul>

<h2>3. Obblighi del Fornitore</h2>
<p>Il Fornitore:</p>
<ul>
    <li>tratta i dati solo su istruzione documentata del Cliente, che consiste nel contratto e nelle operazioni che il Cliente esegue con i servizi, salvo che la legge imponga altrimenti;</li>
    <li>accede ai dati solo quando serve a fornire i servizi, a risolvere un problema segnalato dal Cliente, o a proteggere la sicurezza dei server;</li>
    <li>garantisce che le persone autorizzate al trattamento siano vincolate alla riservatezza;</li>
    <li>adotta le misure di sicurezza adeguate previste dall'art. 32 GDPR, tra cui accesso ai server riservato al personale tecnico con autenticazione, connessioni cifrate, aggiornamenti di sicurezza, isolamento degli account, backup;</li>
    <li>assiste il Cliente, per quanto possibile, nel rispondere alle richieste degli interessati e negli obblighi degli artt. 32-36 GDPR;</li>
    <li>informa il Cliente senza ingiustificato ritardo, e comunque entro 48 ore da quando ne viene a conoscenza, di ogni violazione dei dati personali che riguardi i suoi dati;</li>
    <li>mette a disposizione del Cliente le informazioni necessarie a dimostrare il rispetto di questo accordo e consente verifiche, concordate con un preavviso ragionevole e a spese del Cliente.</li>
</ul>

<h2>4. Obblighi del Cliente</h2>
<p>Il Cliente garantisce di trattare i dati che conserva nei servizi nel rispetto del GDPR, di avere una base giuridica per farlo e di aver informato gli interessati.</p>

<h2>5. Sub-responsabili</h2>
<p>Il Cliente autorizza il Fornitore ad avvalersi dei seguenti sub-responsabili, che ospitano i server:</p>
<ul>
    <li>Leaseweb Deutschland GmbH, Francoforte (Germania);</li>
    <li>Leaseweb Netherlands B.V., Amsterdam (Paesi Bassi);</li>
    <li>WorldStream B.V., Naaldwijk (Paesi Bassi).</li>
</ul>
<p>Il Fornitore impone loro obblighi di protezione dei dati equivalenti a quelli di questo accordo. Comunica al Cliente per email ogni nuovo sub-responsabile almeno 30 giorni prima; il Cliente che si oppone per motivi legati alla protezione dei dati può recedere dal servizio interessato senza costi.</p>

<h2>6. Luogo del trattamento</h2>
<p>I dati sono conservati su server nell'Unione europea. Il Fornitore non li trasferisce fuori dall'Unione europea senza le garanzie previste dal capo V del GDPR.</p>

<h2>7. Fine del trattamento</h2>
<p>Alla cessazione di un servizio il Cliente può scaricare i propri dati fino alla scadenza. Il Fornitore cancella poi i dati secondo i termini delle condizioni generali (artt. 6.3 e 7.6); le copie nei backup sono sovrascritte entro il periodo di conservazione dei backup (art. 9.3), salvo che la legge ne imponga la conservazione.</p>
